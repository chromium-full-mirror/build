const NinjaRulesHelp = `Ninja build rules

The "all" and "default" rules

  All generated targets (see "gn help execution") will be added to an implicit
  build rule called "all" so "ninja all" will always compile everything. The
  default rule will be used by Ninja if no specific target is specified (just
  typing "ninja"). If there is a target named "default" in the root build file,
  it will be the default build rule, otherwise the implicit "all" rule will be
  used.

Phony rules

  GN generates Ninja "phony" rules for targets in the default toolchain.  The
  phony rules can collide with each other and with the names of generated files
  so are generated with the following priority:

    1. Actual files generated by the build always take precedence.

    2. Targets in the toplevel //BUILD.gn file.

    3. Targets in toplevel directories matching the names of the directories.
       So "ninja foo" can be used to compile "//foo:foo". This only applies to
       the first level of directories since usually these are the most
       important (so this won't apply to "//foo/bar:bar").

    4. The short names of executables if there is only one executable with that
       short name. Use "ninja doom_melon" to compile the
       "//tools/fruit:doom_melon" executable.

       Note that for Apple platforms, create_bundle targets with a product_type
       of "com.apple.product-type.application" are considered as executable
       for this rule (as they define application bundles).

    5. The short names of all targets if there is only one target with that
       short name.

    6. Full label name with no leading slashes. So you can use
       "ninja tools/fruit:doom_melon" to build "//tools/fruit:doom_melon".

    7. Labels with an implicit name part (when the short names match the
       directory). So you can use "ninja foo/bar" to compile "//foo/bar:bar".

  These "phony" rules are provided only for running Ninja since this matches
  people's historical expectations for building. For consistency with the rest
  of the program, GN introspection commands accept explicit labels.

  To explicitly compile a target in a non-default toolchain, you must give
  Ninja the exact name of the output file relative to the build directory.
`

// writePhonyAndAllRules generates phony aliases for targets and the all rule.
func writePhonyAndAllRules(out io.Writer, targets []*graph.Target, buildSettings *environment.BuildSettings) error {
	// Track rules as we generate them so we don't accidentally write a phony
	// rule that collides with something else.
	// GN internally generates an "all" target, so don't duplicate it.
	writtenRules := make(map[string]struct{})
	writtenRules["all"] = struct{}{}

	// Set if we encounter a target named "//:default".
	var defaultTarget *graph.Target

	// Targets in the root build file.
	var topLevelTargets []*graph.Target

	// Targets with names matching their toplevel directories. For example
	// "//foo:foo". Expect this is the naming scheme for "big components."
	var topLevelDirTargets []*graph.Target

	type counts struct {
		count    int
		lastSeen *graph.Target
	}

	// Tracks the number of each target with the given short name.
	// Allows skipping phony rules if more than one target generates the same short name.
	shortNames := make(map[string]*counts)

	// Map output file paths to the target that creates it.
	// Used to detect illegal build graphs where multiple distinct targets
	// attempt to generate the exact same output file.
	outputGenerators := make(map[string]*graph.Target)

	for _, target := range targets {
		label := target.Resolution.Label
		shortName := label.Name

		// Register //:default if it exists.
		if label.Dir == buildSettings.RootTargetLabel.Dir && shortName == "default" {
			defaultTarget = target
		}

		// Count the number of targets with the given short name.
		if _, ok := shortNames[shortName]; !ok {
			shortNames[shortName] = &counts{}
		}
		shortNames[shortName].count++
		shortNames[shortName].lastSeen = target

		dirString := label.Dir.Path()
		switch dirString {
		case "//":
			// Register aliases for //:foo, //:bar, //:baz, etc.
			topLevelTargets = append(topLevelTargets, target)
		case "//" + shortName + "/":
			// Register aliases for
			//	dir = //foo/, name = foo
			//	dir = //bar/, name = bar
			//	dir = //baz/, name = baz
			// etc.
			topLevelDirTargets = append(topLevelDirTargets, target)
		}

		// Register outputs of this target.
		// Also validate that targets don't generate the same output file.
		for _, output := range target.Resolution.Metadata.Outputs() {
			outPath := strings.TrimPrefix(output.Path(), "//")

			originalTarget, exists := outputGenerators[outPath]

			// Case 1: First time seeing this output. Register it.
			if !exists {
				outputGenerators[outPath] = target
				writtenRules[outPath] = struct{}{}
				continue
			}

			// Case 2: The same target lists the same output twice. This is harmless.
			if originalTarget == target {
				continue
			}

			// Case 3: Two different targets claim the same output.
			// Current implementation of group() forwards the outputs of their
			// dependencies.
			// So for current impl, true collision only occurs if two distinct targets
			// both have build actions (e.g., compile, link) that try to create the
			// same file.
			if len(originalTarget.Resolution.Actions) > 0 && len(target.Resolution.Actions) > 0 {
				return DuplicateOutputError{
					badOutput: outPath,
					matches:   []*graph.Target{originalTarget, target},
				}
			}
		}
	}

	// First write the names of toplevel targets.
	for _, target := range topLevelTargets {
		name := target.Resolution.Label.Name
		if _, ok := writtenRules[name]; !ok {
			writtenRules[name] = struct{}{}
			writePhonyRule(out, target, name)
		}
	}

	// Next write the names of toplevel dir targets.
	for _, target := range topLevelDirTargets {
		name := target.Resolution.Label.Name
		if _, ok := writtenRules[name]; !ok {
			writtenRules[name] = struct{}{}
			writePhonyRule(out, target, name)
		}
	}

	// Write target short names only when there is exactly one target with that short name.
	for _, shortName := range slices.Sorted(maps.Keys(shortNames)) {
		c := shortNames[shortName]
		if c.count == 1 {
			if _, ok := writtenRules[shortName]; !ok {
				writtenRules[shortName] = struct{}{}
				writePhonyRule(out, c.lastSeen, shortName)
			}
		}
	}

	// Write label variants of target paths.
	for _, target := range targets {
		label := target.Resolution.Label

		// Write the long name "foo/bar:baz" for the target "//foo/bar:baz".
		longName := strings.TrimPrefix(label.UserVisibleString(false), "//")
		if _, ok := writtenRules[longName]; !ok {
			writtenRules[longName] = struct{}{}
			writePhonyRule(out, target, longName)
		}

		// Write the directory name with no target name if they match.
		// e.g "//foo/bar:bar" -> "foo/bar"
		dirString := strings.TrimSuffix(label.Dir.Path(), "/")
		if path.Base(dirString) == label.Name {
			mediumName := strings.TrimPrefix(dirString, "//")
			if mediumName != label.Name {
				if _, ok := writtenRules[mediumName]; !ok {
					writtenRules[mediumName] = struct{}{}
					writePhonyRule(out, target, mediumName)
				}
			}
		}
	}

	// Write the autogenerated "all" rule.
	fmt.Fprint(out, "\nbuild all: phony")
	for _, target := range targets {
		// The "all" rule consists of the "dependency output" of each target,
		// i.e. what file "should be used to express a dependency on" the target.
		// We don't yet have a way of determining this (and it seems necessary
		// for implementing || order only deps), so until it's implemented:
		// - Aggregator targets like group() contribute their phony node
		//   if they have at least one output.
		//   Ninja treats empty phony targets as always dirty, so we still
		//   must check for the output count.
		// - For other targets default to the first output, which is mostly
		//   correct except for rust_proc_macro and shared_library:
		//   https://source.chromium.org/gn/gn/+/main:src/gn/target.cc;l=1000;drc=fa9dacd8eff0bbec4a542c69907659cdd3db8989
		// TODO: fix this once we can determine "dependency outputs".
		// TODO: fix this for rust_proc_macro and shared_library.
		// TODO: right now action() and copy() don't produce phony, but they should too
		// https://source.chromium.org/gn/gn/+/main:src/gn/target.cc;l=971-974;drc=fa9dacd8eff0bbec4a542c69907659cdd3db8989
		outputs := target.Resolution.Metadata.Outputs()
		if len(outputs) > 0 {
			if len(target.Resolution.Actions) == 0 {
				fmt.Fprintf(out, " $\n    %s", escapeStringNinja(phonyTargetPath(target)))
			} else {
				fmt.Fprintf(out, " $\n    %s", escapeStringNinja(outputs[0].Path()))
			}
		}
	}
	fmt.Fprintln(out)

	// Write the default rule if it was set.
	if defaultTarget != nil {
		if _, ok := writtenRules["default"]; ok {
			fmt.Fprintln(out, "\ndefault default")
		} else {
			outputs := defaultTarget.Resolution.Metadata.Outputs()
			if len(outputs) > 0 {
				fmt.Fprintf(out, "\ndefault %s\n", escapeStringNinja(outputs[0].Path()))
			} else {
				fmt.Fprintln(out, "\ndefault ")
			}
		}
	} else if len(targets) > 0 {
		fmt.Fprintln(out, "\ndefault all")
	}

	return nil
}

func writePhonyRule(out io.Writer, t *graph.Target, phonyName string) {
	escaped := escapeStringNinja(phonyName)
	fmt.Fprintf(out, "build %s: phony", escaped)

	outputs := t.Resolution.Metadata.Outputs()
	if len(outputs) > 0 {
		var escapedDeps []string
		for _, output := range outputs {
			escapedDeps = append(escapedDeps, escapeStringNinja(output.Path()))
		}
		fmt.Fprintf(out, " %s", strings.Join(escapedDeps, " "))
	}
	fmt.Fprintln(out)
}

// phonyTargetPath returns the phony target path for a target, e.g. "phony/a/foo" for "//a:foo".
func phonyTargetPath(t *graph.Target) string {
	targetAsPath := strings.TrimPrefix(t.Resolution.Label.Dir.Path(), "//")
	return path.Join("phony", targetAsPath, t.Resolution.Label.Name)
}
