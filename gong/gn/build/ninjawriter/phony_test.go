package ninjawriter

import (
	"errors"
	"strings"
	"testing"

	"github.com/google/go-cmp/cmp"

	"go.chromium.org/build/gong/gn/build/environment"
	"go.chromium.org/build/gong/gn/build/fs"
	"go.chromium.org/build/gong/gn/build/graph"
)

type mockMetadata struct {
	outFiles []fs.OutputPath
}

func (m mockMetadata) Outputs() []fs.OutputPath {
	return m.outFiles
}

func TestWritePhonyAndAllRules(t *testing.T) {
	outDir := mustDir(t, "//out/Default/")

	makeTarget := func(dir, name string, outputs []string, actions []graph.RunToolAction) *graph.Target {
		var outFiles []fs.OutputPath
		for _, out := range outputs {
			outFiles = append(outFiles, fs.MakeOutputPath(outDir, out))
		}
		t := &graph.Target{
			Resolution: graph.Resolution{
				Label: environment.Label{Dir: mustDir(t, dir), Name: name},
				Metadata: mockMetadata{
					outFiles: outFiles,
				},
				Actions: actions,
			},
		}
		return t
	}

	for _, tc := range []struct {
		name    string
		targets []*graph.Target
		want    string
		wantErr any
	}{
		{
			// Priority #1: Actual files generated by the build always take precedence.
			name: "actual",
			targets: []*graph.Target{
				makeTarget("//foo", "actual_file", []string{"foo"}, []graph.RunToolAction{}),
				makeTarget("//foo/foo", "foo", []string{"obj/foo/foo.a"}, []graph.RunToolAction{}),
			},
			// No "foo" generated because that would collide with output from //foo:actual_file
			want: `build actual_file: phony foo
build foo$:actual_file: phony foo
build foo/foo$:foo: phony obj/foo/foo.a
build foo/foo: phony obj/foo/foo.a

build all: phony $
    foo $
    obj/foo/foo.a

default all
`,
		},
		{
			// Priority #2: Targets in the toplevel //BUILD.gn file.
			name: "toplevel",
			targets: []*graph.Target{
				makeTarget("//", "foo", []string{"foo.o"}, []graph.RunToolAction{}),
				makeTarget("//foo/bar", "foo", []string{"bar/foo.o"}, []graph.RunToolAction{}),
			},
			want: `build foo: phony foo.o
build $:foo: phony foo.o
build foo/bar$:foo: phony bar/foo.o

build all: phony $
    foo.o $
    bar/foo.o

default all
`,
		},
		{
			// Priority #3: Targets in toplevel directories matching the names of the directories.
			name: "dirname",
			targets: []*graph.Target{
				makeTarget("//foo", "foo", []string{"foo/foo.o"}, []graph.RunToolAction{}),
				makeTarget("//bar", "foo", []string{"bar/foo.o"}, []graph.RunToolAction{}),
			},
			want: `build foo: phony foo/foo.o
build foo$:foo: phony foo/foo.o
build bar$:foo: phony bar/foo.o

build all: phony $
    foo/foo.o $
    bar/foo.o

default all
`,
		},
		{
			// Priority #4: The short names of executables if there is only one executable with that short name.
			name: "binname",
			targets: []*graph.Target{
				makeTarget("//foo", "bar", []string{"foo/bar.o"}, []graph.RunToolAction{}),
			},
			want: `build bar: phony foo/bar.o
build foo$:bar: phony foo/bar.o

build all: phony $
    foo/bar.o

default all
`,
		},
		{
			// Priority #5: The short names of all targets if there is only one target with that short name.
			name: "shortifunique",
			targets: []*graph.Target{
				makeTarget("//a", "collide", []string{"a/collide.o"}, []graph.RunToolAction{}),
				makeTarget("//b", "collide", []string{"b/collide.o"}, []graph.RunToolAction{}),
				makeTarget("//c", "unique", []string{"c/unique.o"}, []graph.RunToolAction{}),
			},
			want: `build unique: phony c/unique.o
build a$:collide: phony a/collide.o
build b$:collide: phony b/collide.o
build c$:unique: phony c/unique.o

build all: phony $
    a/collide.o $
    b/collide.o $
    c/unique.o

default all
`,
		},
		{
			// Priority #6: Full label name with no leading slashes.
			// Priority #7: Labels with an implicit name part (when the short names match the directory).
			name: "implicit",
			targets: []*graph.Target{
				makeTarget("//a/b/c", "c", []string{"a/b/c/c.o"}, []graph.RunToolAction{}),
			},
			want: `build c: phony a/b/c/c.o
build a/b/c$:c: phony a/b/c/c.o
build a/b/c: phony a/b/c/c.o

build all: phony $
    a/b/c/c.o

default all
`,
		},
		{
			name: "duplicateouts",
			targets: []*graph.Target{
				makeTarget("//a", "foo", []string{"foo.o"}, []graph.RunToolAction{{Tool: "cxx"}}),
				makeTarget("//b", "bar", []string{"foo.o"}, []graph.RunToolAction{{Tool: "cxx"}}),
			},
			wantErr: &DuplicateOutputError{},
		},
		{
			// Current implementation of group() forwards outputs without failing, because they have no actions.
			name: "groupnotduplicate",
			targets: []*graph.Target{
				makeTarget("//a", "foo", []string{"foo.o"}, []graph.RunToolAction{{Tool: "cxx"}}),
				makeTarget("//b", "bar", []string{"foo.o"}, []graph.RunToolAction{}),
			},
			want: `build bar: phony foo.o
build foo: phony foo.o
build a$:foo: phony foo.o
build b$:bar: phony foo.o

build all: phony $
    foo.o $
    foo.o

default all
`,
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			var sb strings.Builder
			err := writePhonyAndAllRules(&sb, tc.targets, &environment.BuildSettings{
				RootPath:        "/test",
				BuildDir:        mustDir(t, "//out/Default"),
				RootTargetLabel: environment.Label{Dir: mustDir(t, "//"), Name: ""},
			})

			wantErr := tc.wantErr != nil
			gotErr := err != nil

			if gotErr != wantErr {
				t.Fatalf("writePhonyAndAllRules()=%v; want %T", err, tc.wantErr)
			}
			if tc.wantErr != nil {
				if !errors.As(err, &tc.wantErr) {
					t.Fatalf("writePhonyAndAllRules()=%v; want %T", err, tc.wantErr)
				}
				return
			}

			if diff := cmp.Diff(tc.want, sb.String()); diff != "" {
				t.Errorf("writePhonyAndAllRules() mismatch (-want +got):\n%s", diff)
			}
		})
	}
}
