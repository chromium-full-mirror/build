package ninjawriter

import (
	"fmt"
	"strings"

	"go.chromium.org/build/gong/gn/build/graph"
)

// DuplicateOutputError is returned when two or more targets generate the same exact output path.
type DuplicateOutputError struct {
	badOutput string
	matches   []*graph.Target
}

// Error returns the error string.
func (e DuplicateOutputError) Error() string {
	var targets []string
	for _, t := range e.matches {
		targets = append(targets, t.Resolution.Label.UserVisibleString(true))
	}
	return fmt.Sprintf("duplicate output file %q generated by %s", e.badOutput, strings.Join(targets, " and "))
}

// Message returns the user-facing error message.
func (DuplicateOutputError) Message() string { return "Duplicate output file." }

// HelpText returns the user-facing error help text.
func (e DuplicateOutputError) HelpText() string {
	var sb strings.Builder
	fmt.Fprintf(&sb, "Two or more targets generate the same output:\n  %s\n\n", e.badOutput)
	fmt.Fprint(&sb, `This can often be fixed by changing one of the target names,
or by setting an explicit output_name on one of them.

The targets are:
`)
	for _, t := range e.matches {
		fmt.Fprintf(&sb, "  %s\n", t.Resolution.Label.UserVisibleString(true))
	}
	return sb.String()
}
